//! `render`: project an environment class's settings from environments.kyaml
//! into the files its platform takes verbatim: a setup script, a
//! Limited-network allowlist and the environment variable names. What a
//! machine should have is rendered here; what it has is doctor's job.

use crate::{Ctx, sha256_hex};
use serde_json::Value;
use std::collections::BTreeMap;

pub const MAX_LINES: usize = 100;
pub const MAX_LINE_BYTES: usize = 200;
pub const MAX_HOSTS: usize = 20;

/// Rendered files for one class, keyed by file name.
pub type Files = BTreeMap<String, String>;

fn s<'a>(v: &'a Value, k: &str, ctx: &str) -> Result<&'a str, String> {
    v[k].as_str()
        .ok_or_else(|| format!("{ctx}: missing string field '{k}'"))
}

/// Single-quote for bash; the manifest never needs a quote inside a value.
fn q(v: &str, ctx: &str) -> Result<String, String> {
    if v.contains('\'') || v.contains('\n') {
        return Err(format!("{ctx}: value contains a quote or newline: {v}"));
    }
    Ok(format!("'{v}'"))
}

fn is_hex64(v: &str) -> bool {
    v.len() == 64
        && v.bytes()
            .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase())
}

fn is_hostname(h: &str) -> bool {
    !h.is_empty()
        && h.len() <= 253
        && h.contains('.')
        && h.split('.').all(|l| {
            !l.is_empty()
                && l.len() <= 63
                && !l.starts_with('-')
                && !l.ends_with('-')
                && l.bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        })
        && !h.split('.').all(|l| l.bytes().all(|b| b.is_ascii_digit()))
}

fn url_host(url: &str) -> Option<&str> {
    url.strip_prefix("https://")?.split(['/', ':', '?']).next()
}

const PRELUDE: &str = r#"set -u
export DEBIAN_FRONTEND=noninteractive
R=/var/lib/bofj-kitt; mkdir -p "$R"; : > "$R/setup-report.tsv"
rep() { # id status detail
  local id="$1" status="$2" detail="$3"
  printf '%s\t%s\t%s\n' "$id" "$status" "$detail" >> "$R/setup-report.tsv"
  case "$status" in
    FAILED|UNAVAILABLE) echo "!!! bofj-kitt setup: $id $status: $detail" >&2 ;;
    *) ;;
  esac; }
apt_pin() { # id package version [link-from link-to]
  local id="$1" pkg="$2" ver="$3" from="${4:-}" to="${5:-}" have
  have="$(dpkg-query -W -f='${Version}' "$pkg" 2>/dev/null)"
  if [[ "$have" == "$ver" ]]; then rep "$id" PRESENT "$pkg=$ver"
  elif apt-get install -y -q --no-install-recommends "$pkg=$ver" >/dev/null 2>&1; then
    rep "$id" INSTALLED "$pkg=$ver"
  else rep "$id" FAILED "apt-get install $pkg=$ver"; return 0; fi
  if [[ -n "$to" ]]; then ln -sf "$from" "$to" || rep "$id" FAILED "link $to"; fi; }
asset() { # id format dest url sha256 [member]
  local id="$1" fmt="$2" dest="$3" url="$4" sha="$5" member="${6:-}" t
  if [[ -e "$R/stamp.$id.$sha" && -e "$dest" ]]; then rep "$id" PRESENT "sha256 $sha"; return 0; fi
  t="$(mktemp -d)"
  if ! curl -fsSL --retry 3 --max-time 900 -o "$t/a" "$url"; then rep "$id" FAILED "download $url"
  elif ! printf '%s  %s\n' "$sha" "$t/a" | sha256sum -c --status -; then
    rep "$id" FAILED "sha256 mismatch for $url"
  elif rm -f "$R/stamp.$id.$sha" && case "$fmt" in
      tar.gz) tar -xzf "$t/a" -C "$t" "$member" && install -m 755 "$t/$member" "$dest" ;;
      tar.zst) rm -rf "$dest" && mkdir -p "$dest" && tar --zstd -xf "$t/a" -C "$dest" --strip-components=1 ;;
      tar.gz-tree) rm -rf "$dest" && mkdir -p "$dest" && tar -xzf "$t/a" -C "$dest" --strip-components=1 ;;
      *) false ;;
    esac; then touch "$R/stamp.$id.$sha"; rep "$id" INSTALLED "sha256 $sha"
  else case "$fmt" in tar.zst|tar.gz-tree) rm -rf "$dest" ;; *) ;; esac
    rep "$id" FAILED "unpack $fmt to $dest"; fi
  rm -rf "$t"; }
apt-get update -q >/dev/null 2>&1 || rep apt-index FAILED "apt-get update"
"#;

fn setup_script(class: &str, r: &Value, manifest_sha: &str) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("#!/bin/bash\n# SPDX-License-Identifier: MPL-2.0\n");
    out.push_str(&format!(
        "# GENERATED by `tools/proof-toolchain/provers.sh render` for {class}; do not edit.\n\
         # Source: tools/environments/environments.kyaml (sha256 {manifest_sha}).\n\
         # Idempotent and non-interactive. Never exits non-zero: each item's outcome\n\
         # goes to /var/lib/bofj-kitt/setup-report.tsv, which doctor reads, and a\n\
         # failure is printed loudly instead of stopping the session from starting.\n"
    ));
    out.push_str(PRELUDE);
    let hosts: Vec<&str> = r["allowed-hosts"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|h| h["host"].as_str())
        .collect();
    for item in r["setup"]
        .as_array()
        .ok_or(format!("{class}: no setup list"))?
    {
        let id = s(item, "id", class)?;
        let ctx = format!("{class} setup {id}");
        match s(item, "via", &ctx)? {
            "apt" => {
                let mut line = format!(
                    "apt_pin {} {} {}",
                    q(id, &ctx)?,
                    q(s(item, "package", &ctx)?, &ctx)?,
                    q(s(item, "version", &ctx)?, &ctx)?
                );
                if !item["link"].is_null() {
                    line.push_str(&format!(
                        " {} {}",
                        q(s(&item["link"], "from", &ctx)?, &ctx)?,
                        q(s(&item["link"], "to", &ctx)?, &ctx)?
                    ));
                }
                out.push_str(&line);
                out.push('\n');
            }
            "asset" => {
                let url = s(item, "url", &ctx)?;
                let sha = s(item, "sha256", &ctx)?;
                if !is_hex64(sha) {
                    return Err(format!("{ctx}: sha256 is not 64 lowercase hex digits"));
                }
                let host = url_host(url).ok_or(format!("{ctx}: url is not https"))?;
                if !hosts.contains(&host) {
                    return Err(format!(
                        "{ctx}: {host} is not in allowed-hosts, so this download would fail under Limited network"
                    ));
                }
                let format = s(item, "format", &ctx)?;
                // Three lines joined by continuations, so a long URL fits the line limit.
                let mut line = format!(
                    "asset {} {} {} \\\n  {} \\\n  {}",
                    q(id, &ctx)?,
                    q(format, &ctx)?,
                    q(s(item, "dest", &ctx)?, &ctx)?,
                    q(url, &ctx)?,
                    sha
                );
                if format == "tar.gz" {
                    line.push_str(&format!(" {}", q(s(item, "member", &ctx)?, &ctx)?));
                } else if format != "tar.zst" && format != "tar.gz-tree" {
                    return Err(format!("{ctx}: unsupported format {format}"));
                }
                out.push_str(&line);
                out.push('\n');
            }
            other => return Err(format!("{ctx}: unsupported via '{other}'")),
        }
    }
    for item in r["unavailable"].as_array().into_iter().flatten() {
        let id = s(item, "id", class)?;
        let reason = s(item, "reason", class)?;
        out.push_str(&format!(
            "rep {} UNAVAILABLE {}\n",
            q(id, class)?,
            q(reason, class)?
        ));
    }
    out.push_str("exit 0\n");
    check_script(&out)?;
    Ok(out)
}

/// The platform's limits and the estate's: checked on every render.
pub fn check_script(script: &str) -> Result<(), String> {
    if script.contains('\r') {
        return Err("setup script has a carriage return; Unix newlines only".into());
    }
    let lines: Vec<&str> = script.lines().collect();
    if lines.len() > MAX_LINES {
        return Err(format!(
            "setup script has {} lines; the limit is {MAX_LINES}",
            lines.len()
        ));
    }
    for (n, l) in lines.iter().enumerate() {
        if l.len() > MAX_LINE_BYTES {
            return Err(format!(
                "setup script line {} is {} bytes; the limit is {MAX_LINE_BYTES}",
                n + 1,
                l.len()
            ));
        }
        if l.contains('\r') || l.chars().any(|c| c.is_control() && c != '\t') {
            return Err(format!(
                "setup script line {} has a control character",
                n + 1
            ));
        }
    }
    for secret in [
        "CLAUDE_SIGNING_KEY",
        "TOKEN",
        "PASSWORD",
        "BEGIN OPENSSH",
        "SECRET",
    ] {
        if script.contains(secret) {
            return Err(format!(
                "setup script mentions {secret}; secrets never go in a setup script"
            ));
        }
    }
    Ok(())
}

fn allowlist(class: &str, r: &Value, env: &Value) -> Result<String, String> {
    let hosts = r["allowed-hosts"]
        .as_array()
        .ok_or(format!("{class}: no allowed-hosts list"))?;
    if hosts.len() > MAX_HOSTS {
        return Err(format!(
            "{class}: {} allowed hosts; the limit is {MAX_HOSTS}",
            hosts.len()
        ));
    }
    let latest = match &env["measured"] {
        Value::Array(a) => a.last().cloned().unwrap_or(Value::Null),
        v => v.clone(),
    };
    let answered: String = ["reachable", "registry-answered"]
        .iter()
        .flat_map(|k| latest[*k].as_array().into_iter().flatten())
        .filter_map(Value::as_str)
        .collect::<Vec<_>>()
        .join("\n");
    let mut out = String::new();
    let mut seen = Vec::new();
    for h in hosts {
        let host = s(h, "host", class)?;
        if !is_hostname(host) {
            return Err(format!(
                "{class}: '{host}' is not an exact lowercase host name"
            ));
        }
        if seen.contains(&host) {
            return Err(format!("{class}: {host} is listed twice"));
        }
        seen.push(host);
        // A host counts as measured when it is a whole token of an answered entry.
        let measured = answered
            .split(|c: char| !(c.is_ascii_alphanumeric() || c == '.' || c == '-'))
            .any(|tok| tok == host);
        if !measured && h["unmeasured"].as_str().is_none() {
            return Err(format!(
                "{class}: {host} was not reachable in the latest measured block ({}); measure it or record why under `unmeasured`",
                latest["date"].as_str().unwrap_or("none")
            ));
        }
        out.push_str(host);
        out.push('\n');
    }
    Ok(out)
}

/// MCP connector endpoints: hosts that plugin connectors reach directly and
/// that the environment's "allow MCP servers" setting does not cover. Kept
/// apart from the toolchain allowlist and its cap. Each host must be exact,
/// listed once, absent from the toolchain list, and say where it was
/// verified. None when the class declares no connector hosts.
fn mcp_allowlist(class: &str, r: &Value) -> Result<Option<String>, String> {
    let Some(declared) = r.get("mcp-connector-hosts") else {
        return Ok(None);
    };
    let Some(list) = declared.as_array() else {
        return Err(format!("{class}: mcp-connector-hosts must be a list"));
    };
    if list.len() > MAX_HOSTS {
        return Err(format!(
            "{class}: {} MCP connector hosts; the limit is {MAX_HOSTS}",
            list.len()
        ));
    }
    let toolchain: Vec<&str> = r["allowed-hosts"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|h| h["host"].as_str())
        .collect();
    let mut seen = Vec::new();
    let mut out = String::new();
    for h in list {
        let host = s(h, "host", class)?;
        if !is_hostname(host) {
            return Err(format!(
                "{class}: MCP connector host '{host}' is not an exact lowercase host name"
            ));
        }
        if seen.contains(&host) || toolchain.contains(&host) {
            return Err(format!(
                "{class}: MCP connector host {host} is listed twice"
            ));
        }
        if s(h, "connector", class)?.is_empty() || s(h, "source", class)?.is_empty() {
            return Err(format!(
                "{class}: MCP connector host {host} needs a connector and a source"
            ));
        }
        seen.push(host);
        out.push_str(host);
        out.push('\n');
    }
    Ok(Some(out))
}

fn env_vars(class: &str, r: &Value) -> Result<String, String> {
    let mut out = String::new();
    for v in r["env-vars"]
        .as_array()
        .ok_or(format!("{class}: no env-vars list"))?
    {
        let name = s(v, "name", class)?;
        if name.is_empty()
            || !name
                .bytes()
                .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit() || b == b'_')
        {
            return Err(format!(
                "{class}: '{name}' is not an environment variable name"
            ));
        }
        let req = if v["required"] == Value::Bool(true) {
            "required"
        } else {
            "optional"
        };
        out.push_str(&format!("{name} {req}\n"));
    }
    Ok(out)
}

/// Render every class that has a `render` block, as path -> contents
/// relative to tools/environments/rendered/.
pub fn render_all(ctx: &Ctx) -> Result<Files, String> {
    let manifest_sha = sha256_hex(ctx.environments_src.as_bytes());
    let blocks = ctx.environments["render"]
        .as_object()
        .ok_or("environments.kyaml: no render block")?;
    let envs = ctx.environments["environments"]
        .as_array()
        .ok_or("environments.kyaml: no environments list")?;
    let mut files = Files::new();
    for (class, r) in blocks {
        let env = envs
            .iter()
            .find(|e| e["id"] == class.as_str())
            .ok_or(format!("render block for undeclared environment '{class}'"))?;
        files.insert(
            format!("{class}/setup.sh"),
            setup_script(class, r, &manifest_sha)?,
        );
        files.insert(
            format!("{class}/allowed-hosts.txt"),
            allowlist(class, r, env)?,
        );
        files.insert(format!("{class}/env-vars.txt"), env_vars(class, r)?);
        let mut lists = vec!["allowed-hosts.txt", "env-vars.txt"];
        if let Some(body) = mcp_allowlist(class, r)? {
            files.insert(format!("{class}/allowed-hosts-mcp.txt"), body);
            lists.push("allowed-hosts-mcp.txt");
        }
        // REUSE sidecars, so the pasteable lists carry no header lines.
        for f in lists {
            files.insert(
                format!("{class}/{f}.license"),
                "SPDX-License-Identifier: MPL-2.0\nGenerated by tools/proof-toolchain/provers.sh render; do not edit.\n".into(),
            );
        }
    }
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mcp_connector_hosts_are_checked() {
        use serde_json::json;
        let ok = json!({"allowed-hosts": [{"host": "github.com"}],
            "mcp-connector-hosts": [{"host": "mcp.notion.com", "connector": "notion", "source": "config"}]});
        assert_eq!(
            mcp_allowlist("c", &ok).unwrap().as_deref(),
            Some("mcp.notion.com\n")
        );
        assert_eq!(mcp_allowlist("c", &json!({})).unwrap(), None);
        for bad in [
            json!({"mcp-connector-hosts": [{"host": "*.notion.com", "connector": "n", "source": "s"}]}),
            json!({"allowed-hosts": [{"host": "github.com"}], "mcp-connector-hosts": [{"host": "github.com", "connector": "n", "source": "s"}]}),
            json!({"mcp-connector-hosts": [{"host": "a.com", "connector": "n", "source": "s"}, {"host": "a.com", "connector": "n", "source": "s"}]}),
            json!({"mcp-connector-hosts": [{"host": "a.com", "connector": "n", "source": ""}]}),
            json!({"mcp-connector-hosts": [{"host": "a.com", "connector": "n"}]}),
            json!({"mcp-connector-hosts": {"host": "a.com"}}),
            json!({"mcp-connector-hosts": "a.com"}),
            json!({"mcp-connector-hosts": null}),
        ] {
            assert!(mcp_allowlist("c", &bad).is_err(), "accepted {bad}");
        }
    }

    #[test]
    fn hostnames_are_exact() {
        assert!(is_hostname("release-assets.githubusercontent.com"));
        for bad in [
            "*.github.com",
            "GitHub.com",
            "localhost",
            "10.0.0.1",
            "a..b",
            "-a.com",
            "a.com/x",
            "a.com:443",
        ] {
            assert!(!is_hostname(bad), "accepted {bad}");
        }
    }

    #[test]
    fn script_limits_are_enforced() {
        assert!(check_script(&"x\n".repeat(MAX_LINES)).is_ok());
        assert!(check_script(&"x\n".repeat(MAX_LINES + 1)).is_err());
        assert!(check_script(&format!("{}\n", "x".repeat(MAX_LINE_BYTES + 1))).is_err());
        assert!(check_script("echo $CLAUDE_SIGNING_KEY\n").is_err());
        assert!(check_script("a\r\n").is_err());
    }

    #[test]
    fn quoting_refuses_quotes() {
        assert!(q("it's", "t").is_err());
        assert_eq!(q("1:9.6p1", "t").unwrap(), "'1:9.6p1'");
    }
}
